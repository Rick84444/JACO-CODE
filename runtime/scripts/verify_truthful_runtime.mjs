import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const checks=[];
const check=(name,ok)=>{checks.push({name,ok}); if(!ok) console.error('FAIL',name); else console.log('PASS',name)};
const server=read('server.ts');
check('pairing validates pairingId and pairingCode',server.includes('verifyPairing(String(req.body?.pairingId') && server.includes("pairing token required"));
check('termux execution has no fake dispatched success',!server.includes('[REAL] Termux bridge command dispatched'));
check('android proxy uses explicit allowlist',server.includes('ANDROID_PROXY_PORTS.has(targetPort)'));
check('computer bridge has no fabricated offline model list',server.includes('installedModels: isOllamaOnline ? ollamaModels : []'));
check('ISO build does not synthesize checksum',!server.includes('a1b2c3d4e5f67890123456789abcdef'));
check('Cloudflare does not synthesize trycloudflare domain',!server.includes("const domain = hostname || `ollama-"));
check('job reaper starts',server.includes('startJobReaper();'));
const mock=read('src/mockData.ts');
check('startup model list evidence-empty',/INITIAL_MODELS:\s*OllamaModel\[\]\s*=\s*\[\]/.test(mock));
check('startup device list evidence-empty',/INITIAL_DEVICES:\s*SocketDevice\[\]\s*=\s*\[\]/.test(mock));
const econ=['src/server/economic/economicLedger.ts','src/server/economic/productRegistry.ts','src/server/economic/entitlementEngine.ts','src/server/economic/stripeAuthority.ts'].filter(p=>fs.existsSync(path.join(root,p))).map(read).join('\n'); // removed modules cannot hold stubs
check('economic stubs removed',!/(mockhash|mocktoken|checkout\.stripe\.com\/mock|name:\s*['"]Mock['"])/i.test(econ));
check('stub generator removed',!fs.existsSync(path.join(root,'create_economic_stubs.cjs')));
const forge=read('src/server/forge/jacoForge.ts');
check('unsupported forge journey fails closed',forge.includes("step.status = 'FAILED'") && !forge.includes('Deterministic mock verification'));
const android=read('src/server/android/androidDeviceAgent.ts');
check('torch cannot claim container-only hardware success',!android.includes('Device state registered in container runtime'));
const seer=read('src/server/seer/seerService.ts');
check('SEER has no fabricated default active goal',seer.includes('GOAL-UNCONFIGURED') && !seer.includes("progress: 0.65"));
check('SEER exposes evidence state',seer.includes('evidenceState:'));
if(checks.some(c=>!c.ok)) process.exit(1);
console.log(`truthful-runtime: PASS (${checks.length}/${checks.length})`);
